# #1. Tạo frame
data ={
    "Họ_và_tên" : [ "An",  "Duy", "Được", "Hào", "Huy", "Minh",  "Nam", "Tài", "Tuấn", "Tuệ", ],
    "Chuyen_can" : [8.0, 9.0, 7.5, 6.0, 8.5, 9.5, 7.0, 6.5, 8.0, 9.0],
    "Giua_ky" : [7.0, 8.0, 6.5, 5.5, 8.0, 9.0, 6.0, 5.0, 7.5, 8.5],
    "Cuối_kỳ" : [7.5, 8.5, 7.0, 5.0, 8.5, 9.0, 6.5, 5.5, 8.0, 9.0],}
df = pd.DataFrame(data)

print("--- Bảng dữ liệu gốc ---")
print(df)
print("\n" + "="*50 + "\n")

# #2. Tính điểm tổng kết
df["Tong ket"] = (
     0.2 * df['Chuyen_can'] + 0.3 * df['Giua_ky'] + 0.5 * df[ "Cuối_kỳ" ])

print("--- Bảng dữ liệu sau khi tính tổng kết ---")
print(df)
print("\n" + "="*50 + "\n")

# #3. xếp loại sinh viên
def xep_loai (diem):
  if diem >= 8.5:
    return "gioi"
  elif diem >= 7.0:
    return "kha"
  elif diem >= 5.0:
    return "trung binh"
  else:
     return "yeu"
df['xep_loai'] = df["Tong ket"].apply(xep_loai)
print("--- Bảng dữ liệu sau khi xếp loại ---")
print(df)
print("\n" + "="*50 + "\n")

# #4. Thống kê
diem_trung_binh_lop = df["Tong ket"] .mean()
sv_cao_nhat = df.loc[df["Tong ket"].idxmax()]
sv_thap_nhat = df.loc[df["Tong ket"] .idxmin()]
so_SV_dat = (df["Tong ket"] >= 5.0) .sum()

print("--- Kết quả thống kê lớp học ---")
print(f"- Điểm tổng kết trung bình của lớp: {diem_trung_binh_lop:.2f}")
print(f"- sinh viên có điểm cao nhất: {sv_cao_nhat['Họ_và_tên']} ({sv_cao_nhat["Tong ket"]} điểm)")
print(f"- sinh viên có diểm thấp nhất: {sv_thap_nhat['Họ_và_tên']} ({sv_thap_nhat["Tong ket"]} điểm)")
print(f"- số sinh viên đạt (>= 5.0): {so_SV_dat} / {len(df)} sinh viên")

